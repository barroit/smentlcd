from os import scandir
from os.path import relpath
from sys import argv

def find_child(ents):
	child = set()

	for ent in ents:
		if ent.is_file() and not ent.name.endswith('_entry.c'):
			child.add(f"{ent.path}")

	return child

def find_subtree(ents):
	subtree = set()

	for ent in ents:
		if ent.is_dir():
			subtree.add(f"{ent.path}.c")

	return subtree

node = argv[1]
node_name = node.replace('/', '_')
script = relpath(__file__)

__ents = scandir(node)
ents = list(__ents)

__child = find_child(ents)
child = sorted(__child)

__subtree = find_subtree(ents)
subtree = sorted(__subtree)

__leaf = __child ^ __subtree
leaf = sorted(__leaf)

iter = None
str = None

print(f"# Generated by {argv[0]}\n")

iter = map(lambda file: f"build/{file[0:-1]}o", leaf)
str = ' '.join(iter)
print(f"cmd-obj-{node_name} := build/{node}.o {str}", end='')

for tree in subtree:
	name = tree[0:-2].replace('/', '_')

	print(f" $(cmd-obj-{name})", end='')
print('\n')

iter = map(lambda file: f"build/{file[0:-1]}o", leaf)
str = ' '.join(iter)
print(f"obj-cmd += build/{node}.o {str}\n")

print(f"build/{node}/.cmdnode: build/{node}/.cmdlist {script}\n")

for file in leaf:
	name = file[0:-2]

	print(f"build/{name}.o: include/generated/{name}/cmddecl.h")
print()

print(f"build/{node}.o: include/generated/{node}/cmdtab.h\n")

print(f"build/{node}/entry: build/{node}_entry.o $(cmd-obj-{node_name}) |",
      end='')

iter = map(lambda file: f"build/{file[0:-2]}/entry", subtree)
str = ' '.join(iter)
print(f" {str}")
