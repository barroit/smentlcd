from os import scandir
from sys import argv

def make_cmdtree(parent):
	__ents = scandir(parent)
	ents = sorted(__ents, key=lambda ent: ent.name)

	for ent in ents:
		if ent.is_dir():
			dep = f"build/{ent.path}/.cmdnode"

			make_cmdtree(ent.path)
			print(f"include $(if $(wildcard {ent.path}/),{dep})")


print(f"# Generated by {argv[0]}\n")

make_cmdtree(argv[1])
